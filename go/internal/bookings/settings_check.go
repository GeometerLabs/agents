//go:embed settings_check.json
var checkJSON []byte

// checkWords is settings_check.json: the character's styles with their palettes, the personalities and the paints.
var checkWords = func() (w struct {
	Styles []struct {
		ID      string   `json:"id"`
		Name    string   `json:"name"`
		Palette []string `json:"palette"`
	} `json:"styles"`
	Personalities []string `json:"personalities"`
	Paints        []string `json:"paints"`
	MaxPeople     int      `json:"maxPeople"`
	OwnerApprover string   `json:"ownerApprover"`
}) {
	if err := json.Unmarshal(checkJSON, &w); err != nil {
		panic("settings_check.json: " + err.Error())
	}
	return
}()

func hasKey(m map[string]any, k string) bool { _, ok := m[k]; return ok }

var (
	whatsappRe = regexp.MustCompile(`^\+\d{10,15}$`)
	personRe   = regexp.MustCompile(`^[a-z][a-z0-9-]{0,31}$`)
	nameRe     = regexp.MustCompile(`^[\p{L}\p{M}][\p{L}\p{M} '’-]{0,23}$`)
	seedRe     = regexp.MustCompile(`^[a-z0-9][a-z0-9-]{0,79}$`)
	morningRe  = regexp.MustCompile(`^([01]\d|2[0-3]):([0-5]\d)$`)
)

func digitsOf(s string) string {
	var b strings.Builder
	for _, c := range s {
		if c >= '0' && c <= '9' {
			b.WriteRune(c)
		}
	}
	return b.String()
}

// keysIn is Object.keys of an object: the file's order when known (path), else sorted.
func (r *reader) keysIn(m map[string]any, order func(string) []string, path string) []string {
	return keysOf(m, order(path))
}

// approvers is readApprovers(input.approvers, {ownerWhatsapp, refundLimitInr}, errors): who else may approve a refund Guard holds, checked. `given` tells a missing key from a JSON null.
func (r *reader) approvers(v any, given bool, order func(string) []string, s *Settings) {
	if !given {
		return
	}
	const where = "approvers"
	before := len(r.errs)
	obj, ok := isObj(v)
	if !ok {
		r.add(`"%s" must look like {"people": [{"id": "ravi", "whatsapp": "+919800000002", "language": "hi"}], "twoAboveInr": 2000}. Leave it out and the owner alone approves.`, where)
		return
	}
	for _, k := range r.keysIn(obj, order, "/approvers") {
		if k != "people" && k != "twoAboveInr" {
			r.add(`I don't know what %q means in "%s". Allowed: people, twoAboveInr.`, k, where)
		}
	}
	list, isList := obj["people"].([]any)
	if !isList || len(list) == 0 || len(list) > checkWords.MaxPeople {
		r.add(`"%s.people" must list 1 to %d people besides the owner, each with an id, a WhatsApp number and a language.`, where, checkWords.MaxPeople)
		return
	}
	people := []any{}
	ids := map[string]bool{}
	numbers := map[string]bool{}
	if s.Owner.Whatsapp != "" {
		numbers[digitsOf(s.Owner.Whatsapp)] = true
	}
	for i, raw := range list {
		at := fmt.Sprintf("%s.people[%d]", where, i)
		p, ok := isObj(raw)
		if !ok {
			r.add(`%s must be {"id": "ravi", "whatsapp": "+919800000002", "language": "hi"}.`, at)
			continue
		}
		for _, k := range r.keysIn(p, order, "/approvers/people/"+strconv.Itoa(i)) {
			if k != "id" && k != "whatsapp" && k != "language" {
				r.add(`I don't know what %q means in %s. Allowed: id, whatsapp, language.`, k, at)
			}
		}
		id, idIsS := p["id"].(string)
		switch {
		case !idIsS || !personRe.MatchString(id) || id == checkWords.OwnerApprover:
			r.add(`%s.id must be a short name in lower-case letters, digits and hyphens, starting with a letter (for example "ravi"), and not "%s".`, at, checkWords.OwnerApprover)
		case ids[id]:
			r.add(`%s.id "%s" is listed twice: each person has their own id.`, at, id)
		default:
			ids[id] = true
		}
		wa, waIsS := p["whatsapp"].(string)
		switch {
		case !waIsS || !whatsappRe.MatchString(wa):
			r.add(`%s.whatsapp must start with + and the country code, then digits only, for example +919800000002.`, at)
		case numbers[digitsOf(wa)]:
			r.add(`%s.whatsapp is already the owner's or another person's number: each person answers from their own phone.`, at)
		default:
			numbers[digitsOf(wa)] = true
		}
		var lang any = "en" // `p.language ?? "en"`: a missing or null language is English
		if l, has := p["language"]; has && l != nil {
			lang = l
		}
		ls, langIsS := lang.(string)
		langOK := langIsS && contains(runtime.LANGUAGES, ls)
		if !langOK {
			r.add(`%s.language must be one of %s.`, at, strings.Join(runtime.LANGUAGES, ", "))
		}
		if idIsS && waIsS && langOK {
			people = append(people, map[string]any{"id": id, "whatsapp": wa, "language": ls})
		}
	}
	var two any
	if tv, has := obj["twoAboveInr"]; has {
		n, whole := isWhole(tv)
		switch {
		case !whole || n < 0 || n > 10_000_000:
			r.add(`"%s.twoAboveInr" must be a whole number of rupees: refunds above it need two different people.`, where)
		case s.refundLimitOK && n < s.Cancellation.RefundLimitInr:
			r.add(`"%s.twoAboveInr" (₹%d) is below the refund limit (₹%d). Up to the refund limit the agent refunds alone, so two people can only be asked above it: make it ₹%d or more.`, where, n, s.Cancellation.RefundLimitInr, s.Cancellation.RefundLimitInr)
		default:
			two = float64(n)
		}
	}
	if len(r.errs) > before {
		return
	}
	out := map[string]any{"people": people}
	if two != nil {
		out["twoAboveInr"] = two
	}
	s.Approvers = out
}

// assistant is readAssistantSettings: the `assistant` block, checked, and returned as the checked form (`morningAt`, the character, `talk` only when it is off).
func (r *reader) assistant(v any, given bool, order func(string) []string, s *Settings) {
	if !given {
		return
	}
	raw, ok := isObj(v)
	if !ok {
		r.add(`"assistant" must be an object (it may be empty: {} turns the shop's assistant on with its defaults).`)
		return
	}
	for _, k := range r.keysIn(raw, order, "/assistant") {
		if k != "morning" && k != "character" && k != "talk" {
			r.add(`"assistant" has %q, which is not a setting (morning, character, talk).`, k)
		}
	}
	var morning any = map[string]any{"hour": 8.0, "minute": 0.0} // DEFAULT_MORNING
	if mv, has := raw["morning"]; has {
		if b, isB := mv.(bool); isB && !b {
			morning = nil
		} else {
			var at any
			if m, isM := isObj(mv); isM {
				at = m["at"]
			}
			var hit []string
			if as, isS := at.(string); isS {
				hit = morningRe.FindStringSubmatch(as)
			}
			if hit == nil {
				r.add(`"assistant.morning" must be {"at": "HH:MM"} (24-hour, the shop's time) or false for no morning line.`)
			} else {
				h, _ := strconv.Atoi(hit[1])
				m, _ := strconv.Atoi(hit[2])
				morning = map[string]any{"hour": float64(h), "minute": float64(m)}
			}
		}
	}
	customers := true
	if tv, has := raw["talk"]; has {
		t, isT := isObj(tv)
		bad := !isT
		if isT {
			for k := range t {
				bad = bad || k != "customers"
			}
			if c, has := t["customers"]; has {
				if _, isB := c.(bool); !isB {
					bad = true
				}
			}
		}
		if bad {
			r.add(`"assistant.talk" must be {"customers": true} or {"customers": false}: false turns the assistant's own answers off for customers (they get the menu), true is the default.`)
		} else if c, isB := t["customers"].(bool); isB && !c {
			customers = false
		}
	}
	character := r.character(raw["character"], hasKey(raw, "character"), order)
	if character == nil {
		character = map[string]any{"style": "clay", "personality": "warm"} // defaultCharacter()
	}
	out := map[string]any{"morningAt": morning, "character": character}
	if !customers {
		out["talk"] = map[string]any{"customers": false}
	}
	s.Assistant = out
}

// character is readCharacter: a character setting, checked; a missing part takes its default. nil when it is left out or not an object.
func (r *reader) character(v any, given bool, order func(string) []string) map[string]any {
	if !given {
		return nil
	}
	raw, ok := isObj(v)
	if !ok {
		r.add(`"assistant.character" must be an object with a style (and, if you like, a name).`)
		return nil
	}
	keys := []string{"name", "style", "seed", "colour", "paint", "personality"}
	for _, k := range r.keysIn(raw, order, "/assistant/character") {
		if k == "look" {
			r.add(`"assistant.character.look" is no longer a setting: the character is a DiceBear "style", a "seed" and a "colour" (decision 47). Make it again in the panel's Character step.`)
		} else if !contains(keys, k) {
			r.add(`"assistant.character" has %q, which is not a setting (%s). The assistant answers in text, so there is no voice to choose.`, k, strings.Join(keys, ", "))
		}
	}
	// the name is optional: left out or empty, the assistant is "<the shop>'s assistant"
	name, nameOK := "", true
	if nv, has := raw["name"]; has {
		if ns, isS := nv.(string); isS {
			name = language.TrimJS(ns)
		} else {
			nameOK = false
		}
	}
	if !nameOK || (name != "" && !nameRe.MatchString(name)) {
		r.add(`The character's "name" must be 1 to 24 letters (spaces, hyphens and apostrophes are fine; no digits), or left out.`)
	}
	styleIDs := make([]string, len(checkWords.Styles))
	for i, st := range checkWords.Styles {
		styleIDs[i] = st.ID
	}
	var style any = "clay"
	if sv, has := raw["style"]; has {
		style = sv
	}
	styleS, styleIsS := style.(string)
	styleOK := styleIsS && contains(styleIDs, styleS)
	if !styleOK {
		r.add(`The character's "style" must be one of: %s.`, strings.Join(styleIDs, ", "))
	}
	out := map[string]any{"style": "clay", "personality": "warm"}
	if styleOK {
		out["style"] = styleS
	}
	if name != "" {
		out["name"] = name
	}
	if sv, has := raw["seed"]; has {
		if ss, isS := sv.(string); !isS || !seedRe.MatchString(ss) {
			r.add(`The character's "seed" must be 1 to 80 small letters, digits and hyphens.`)
		} else {
			out["seed"] = ss
		}
	}
	if cv, has := raw["colour"]; has {
		c := ""
		if cs, isS := cv.(string); isS {
			c = strings.ToLower(strings.TrimPrefix(cs, "#"))
		}
		info := checkWords.Styles[0]
		for _, st := range checkWords.Styles {
			if st.ID == out["style"] {
				info = st
			}
		}
		if !contains(info.Palette, c) {
			r.add(`The character's "colour" must be one of the %s colours (%s), or left out for DiceBear's own.`, info.Name, strings.Join(info.Palette, ", "))
		} else {
			out["colour"] = c
		}
	}
	if pv, has := raw["paint"]; has {
		if ps, isS := pv.(string); !isS || !contains(checkWords.Paints, ps) {
			r.add(`The character's "paint" must be one of: %s, or left out for the head's own green.`, strings.Join(checkWords.Paints, ", "))
		} else {
			out["paint"] = ps
		}
	}
	if pv, has := raw["personality"]; has {
		if ps, isS := pv.(string); !isS || !contains(checkWords.Personalities, ps) {
			r.add(`The character's "personality" must be one of: %s.`, strings.Join(checkWords.Personalities, ", "))
		} else {
			out["personality"] = ps
		}
	}
	return out
}

// Tree is the validated settings as the JSON value validateSettings returns: what the policy digest is of (bookingsreport.PolicyDigest), and what the monthly report reads.
func (s *Settings) Tree() map[string]any {
	num := func(n int64) any { return float64(n) }
	services := make([]any, len(s.Services))
	for i, sv := range s.Services {
		names := map[string]any{}
		for lang, list := range sv.Names {
			l := make([]any, len(list))
			for j, n := range list {
				l[j] = n
			}
			names[lang] = l
		}
		out := map[string]any{"id": sv.ID, "names": names, "priceInr": num(sv.PriceInr), "durationMinutes": num(sv.DurationMinutes)}
		if sv.Resource != "" {
			out["resource"] = sv.Resource
		}
		services[i] = out
	}
	hours := map[string]any{}
	for i, day := range WeekdayKeys {
		if h := s.OpeningHours[i]; h != nil {
			hours[day] = map[string]any{"open": h.OpenText, "close": h.CloseText}
		} else {
			hours[day] = nil
		}
	}
	languages := make([]any, len(s.Languages))
	for i, l := range s.Languages {
		languages[i] = l
	}
	before := make([]any, len(s.Reminders))
	for i, h := range s.Reminders {
		before[i] = num(h)
	}
	payment := map[string]any{"module": s.Payment.Module}
	if s.Payment.Module == "upi" {
		payment["upi"] = map[string]any{"id": s.Payment.UpiID, "payee": s.Payment.Payee}
	}
	t := map[string]any{
		"name": s.Name, "timezone": s.Timezone, "services": services, "openingHours": hours, "slotMinutes": num(s.SlotMinutes), "bufferMinutes": num(s.BufferMinutes),
		"deposit":      map[string]any{"amountInr": num(s.Deposit.AmountInr), "holdMinutes": num(s.Deposit.HoldMinutes)},
		"cancellation": map[string]any{"windowHours": num(s.Cancellation.WindowHours), "refundLimitInr": num(s.Cancellation.RefundLimitInr)},
		"languages":    languages, "owner": map[string]any{"whatsapp": s.Owner.Whatsapp, "language": s.Owner.Language},
		"reminders": map[string]any{"hoursBefore": before}, "payment": payment,
	}
	if s.HasAddress {
		t["address"] = s.Address
	}
	if s.Resources != nil {
		res := map[string]any{}
		for k, n := range s.Resources {
			res[k] = num(n)
		}
		t["resources"] = res
	}
	if s.Approvers != nil {
		t["approvers"] = s.Approvers
	}
	if s.calendarGiven {
		t["calendar"] = map[string]any{"module": s.Calendar}
	}
	if s.Assistant != nil {
		t["assistant"] = s.Assistant
	}
	return t
}

// CheckSettingsFile is validateSettings over the text of settings.json: the checked settings and their tree, or every problem in plain words (a file that is not JSON says so).
func CheckSettingsFile(raw []byte) (*Settings, map[string]any, []string) {
	var v any
	if err := json.Unmarshal(raw, &v); err != nil {
		return nil, nil, []string{"The settings file is not valid JSON: " + err.Error()}
	}
	in, ok := v.(map[string]any)
	if !ok {
		return nil, nil, []string{"The settings must be an object with the business's name, services, hours and so on."}
	}
	s, errs := ReadSettings(in, raw)
	if len(errs) > 0 {
		return nil, nil, errs
	}
	return s, s.Tree(), nil
}
