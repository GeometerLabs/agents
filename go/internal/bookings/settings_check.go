package bookings

// The rest of validateSettings (templates/commerce/bookings/src/settings.ts) that settings.go leaves out, and the CHECKED TREE it returns.
//
// Why a tree: the report's policy digest (bookingsreport.PolicyDigest) is the digest of the settings AS VALIDATED, not as the file was written: validateSettings fills the defaults (the
// time zone, `bufferMinutes` 0, `languages`, the deposit's hold, the owner's language, the reminders), trims the name, keeps each service's names in the shop's languages only, reads the
// payment block (a UPI ID lower-cased) and hands `approvers` and `assistant` back in their checked forms (the assistant's `morning` becomes `morningAt`, its character gets its defaults).
// A raw settings.json gives another digest, and a go-live certificate of the same settings (which the CLI makes from the validated settings) would read as "different".
// `(*Settings).Tree` writes the validated settings as that JSON tree (numbers as float64, as JSON.parse reads them), the value the report is handed; the vectors in
// testdata/settings-tree-vectors.json (go/scripts/gen_bookings_settings.ts) hold its digest equal to the TypeScript's on the shops there.
//
// Here as well: readApprovers (modules/approvals/people.ts), readAssistantSettings (modules/assistant/settings.ts) and readCharacter (modules/assistant/character.ts) with their
// sentences, in the order validateSettings calls them (the approvers after the owner, the assistant last), so a file with several problems says them in the TypeScript's order.
// The styles, their palettes, the personalities and the paints are the TypeScript's own lists (settings_check.json, generated by gen_bookings_settings.ts: nothing is retyped).
//
// Where Go and JavaScript differ: `.trim()` is language.TrimJS; the character's name is checked with RE2's `\p{L}\p{M}` (the same classes the `u` flag gives); an object's keys are
// read in the order the file names them (ordered(), as settings.go does); `digits` removes everything but ASCII digits, as `\D` with the `u` flag does.

