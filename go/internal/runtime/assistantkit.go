package runtime

// The skill seam of the owner's assistant (modules/assistant/skill.ts OwnerSkill, wire.ts assistantForAgent): what a template's agent gives the assistant so the ONE
// conversation in assistant.go serves every shop. The listings-only shop (no Kit) has one built-in skill, its listings, and talks on its page only. A template (Bookings, wave 2)
// hands in its own skill and its ways out through StepContext.Assistant; the assistant then hosts [the template's skill, the declared limits, the listings], in wire.ts's order,
// answers on WhatsApp through the shared say (messaging.Say, say.ts) with its own words, and on the owner's page when the owner acts from there.
//
// The skill's two halves are kept apart as skill.ts keeps them: the READS (a day's list, what waits) are pure over the step's store; the ACTS change something. `Prepare` turns
// what the owner asked into the EXACT action from the store, or says why it cannot be done; `Execute` does a prepared action through the template's own paths (the same limits,
// Guards and words as the fixed phrases). A card is made from Prepare, and on the tap Prepare runs again and must give the same digest (assistant.JudgeCard) before Execute.
//
// What the assistant says is written from the packed words (internal/assistant/words, generated by go/scripts/gen_words.ts from words.ts), filled with the shop's own saved
// values. Every line goes through the outgoing check (message-matches-record, language.CheckText) with the facts its writer noted (internal/assistant/writer.go: the key's own
// facts generated from the TypeScript, and the values put in), on the page and on WhatsApp, as conversation.ts does; the talk's reply carries the facts its sources allowed.

