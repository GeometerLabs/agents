// onPage is conversation.ts onPage: while the owner acts from their page, the answers go to the page's talk and not to WhatsApp.
func (c *conv) onPage(fn func()) {
	was := c.toPage
	c.toPage = true
	defer func() { c.toPage = was }()
	fn()
}

// idOf is the words.ts message id a packed key belongs to (the record's `templates` names it as `assistant_<id>`).
func idOf(key string) string {
	id := strings.TrimSuffix(key, "@bookings")
	if i := strings.IndexByte(id, '.'); i >= 0 {
		id = id[:i]
	}
	switch id {
	case "limit_which":
		return "limit"
	case "budget":
		return "budget_line"
	case "listing_refused":
		return "listing_line"
	}
	return id
}

// tellText is conversation.ts `tell` with the words already written: to the page's talk while the owner acts from their page (a card is never a line there: it is in the page's
// own list), otherwise to the owner on WhatsApp, with buttons when it is a card. Returns whether it went.
func (c *conv) tellText(id, text, caseID string, buttons []messaging.Choice) bool {
	if c.toPage || c.hooks == nil {
		if id == "card" {
			return true
		}
		c.a.AddTalk("assistant", text, c.now)
		return true
	}
	line := &saidLine{caseID: caseID, write: func(string) saidFacts { return saidFacts{text: text} }, buttons: buttons}
	args := &messaging.SayArgs{Booking: line, Phone: c.number, To: "owner", Templates: []string{"assistant_" + id}, Extra: line}
	if len(buttons) > 0 {
		args.Offer = &messaging.Offer{Kind: "card"}
	}
	went, err := c.waSay().Say(context.Background(), args)
	return err == nil && went
}

// tellCustomer is conversation.ts tellCustomer: a customer's line about their booking on a closed or reopened day, the assistant's approved template so it can go outside their
// window too. The words are in the customer's language.
func (c *conv) tellCustomer(id, caseID, phone string, d LocalDate, startMs int64) bool {
	shop := c.r.o.Client.Settings.Name
	line := &saidLine{caseID: caseID, write: func(lang string) saidFacts {
		p := assistant.Words(lang)
		date := p.DateText(d.Year, d.Month, d.Day)
		t := time.UnixMilli(startMs).In(c.r.loc)
		tm := p.TimeOfDay(t.Hour(), t.Minute())
		vals := map[string]string{"shop": shop, "date": date, "time": tm}
		var params []string
		for _, k := range strings.Split(p.Say("tmpl."+id+".order"), ",") {
			params = append(params, vals[k])
		}
		return saidFacts{text: p.Say("tmpl."+id, "shop", shop, "date", date, "time", tm), template: &messaging.TemplateMessage{Name: p.Say("tmpl." + id + ".name"), Language: lang, Parameters: params}}
	}}
	args := &messaging.SayArgs{Booking: line, Phone: phone, To: "customer", Templates: []string{"assistant_" + id}, Extra: line}
	went, err := c.waSay().Say(context.Background(), args)
	return err == nil && went
}

// tellCustomerWords is a message card's yes (conversation.ts sendWords): the owner's words, as typed, under the shop's name, in the customer's language's frame.
func (c *conv) tellCustomerWords(caseID, phone, words string) bool {
	shop := c.r.o.Client.Settings.Name
	line := &saidLine{caseID: caseID, write: func(lang string) saidFacts {
		return saidFacts{text: assistant.Words(lang).Say("owner_words", "shop", shop, "words", words)}
	}}
	args := &messaging.SayArgs{Booking: line, Phone: phone, To: "customer", Templates: []string{"assistant_owner_words"}, Extra: line}
	went, err := c.waSay().Say(context.Background(), args)
	return err == nil && went
}

// saidLine is conversation.ts `Said`: the case the line is about and the words, written for the language say picks.
type saidLine struct {
	caseID  string
	write   func(lang string) saidFacts
	buttons []messaging.Choice
}

// saidFacts is conversation.ts SaidFacts: the text, and the approved template that carries it outside the window (nil: none, so it goes only inside the window).
type saidFacts struct {
	text     string
	template *messaging.TemplateMessage
}

// assistantVoice is conversation.ts sayVoice.
type assistantVoice struct{}

func (assistantVoice) Render(_ string, facts any) (string, error) { return facts.(saidFacts).text, nil }

func (assistantVoice) TemplateMessage(t messaging.TemplateArgs) (messaging.TemplateMessage, error) {
	f := t.Facts.(saidFacts)
	if f.template == nil {
		return messaging.TemplateMessage{}, errors.New("this reply has no approved WhatsApp template, so it goes only while the person's 24-hour window is open")
	}
	m := *f.template
	m.Text = t.Text
	return m, nil
}

func (assistantVoice) GenericNames() messaging.GenericNames {
	return messaging.GenericNames{Customer: "assistant_no_template", Reminder: "assistant_no_template", Owner: "assistant_no_template"}
}

// Matches is the outgoing check's verdict: every value in the assistant's words was put there from the record by this code (the file's head says why it is not read again).
func (assistantVoice) Matches(string, any) messaging.Decision {
	return messaging.Decision{RuleID: "message-matches-record", Verdict: "allow", Reason: "every value in the message is on the record"}
}

// waSay is conversation.ts's createSay over the agent's messaging, made once per step.
func (c *conv) waSay() *messaging.Say {
	if c.say_ != nil {
		return c.say_
	}
	h := c.hooks
	owner := c.number
	c.say_ = messaging.NewSay(messaging.SayDeps{
		Messaging: h.Messaging, Voice: assistantVoice{}, Owner: messaging.OwnerInfo{WhatsApp: owner, Language: c.lang},
		LanguageOf: func(phone string, _ any) string {
			if phone == owner {
				return c.lang
			}
			return h.LanguageOf(phone)
		},
		OptedOut: func(phone string) bool { return phone != owner && h.OptedOut(phone) },
		FactsFor: func(a *messaging.SayArgs, lang string) (any, error) { return a.Extra.(*saidLine).write(lang), nil },
		InteractiveFor: func(a *messaging.SayArgs, facts any, _ string) (*messaging.InteractiveMessage, error) {
			return &messaging.InteractiveMessage{Body: facts.(saidFacts).text, Buttons: a.Extra.(*saidLine).buttons}, nil
		},
		Log: func(booking any, phone, action, outcome string, inputs map[string]any, more messaging.LogMore) {
			caseID := ""
			if l, ok := booking.(*saidLine); ok {
				caseID = l.caseID
			}
			h.Log(caseID, phone, action, outcome, inputs, more)
		},
		HeldBack: func(context.Context, *messaging.SayArgs) error { return nil }, // the assistant's own words held back are in the record; the owner sees the result in the reply
	})
	return c.say_
}

// windowOpen is conversation.ts windowOpen: a failure to ask is a closed window.
func (c *conv) windowOpen(phone string) bool {
	if c.hooks == nil || c.hooks.Messaging == nil {
		return false
	}
	open, err := c.hooks.Messaging.IsWindowOpen(context.Background(), phone)
	return err == nil && open
}
