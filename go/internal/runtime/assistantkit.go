// Shown is what a card says, from the same fields as its action (skill.ts Prepared.shown).
type Shown struct {
	Who, What   string
	AmountPaise int64
	Words       string // a message's words, shown as typed
	HasWords    bool
	Limit       *LimitCardView // a limit card: the rule, its value now and the proposed one
}

// Prepared is skill.ts Prepared when ok: the exact action and what the owner is shown.
type Prepared struct {
	Action     assistant.Action
	Shown      Shown
	AboveLimit bool
	// RefusedPaidPaise is skill.ts's refusal `paidPaise`: with the refusal "too_much", what was paid on the payment the refund would come from, for the owner's words
	// ("That is more than was paid on f-2 (₹1,800)."). Zero says ₹0, as the TypeScript's `?? 0` does.
	RefusedPaidPaise int64
}

// Executed is skill.ts Executed: whether it worked and the note the owner's answer is worded by (done, held_by_guard, owed_by_owner, sent, failed, not_sent).
type Executed struct {
	OK   bool
	Note string
}

// WaitingItem is skill.ts WaitingItem: something that waits for the owner, as a card can show it.
type WaitingItem struct {
	Case, Kind, Who, What string
	AmountPaise           int64
	Money                 bool   // it is about money (every Bookings item is)
	Yes, No               string // the owner's own fixed replies ("approve" / "deny"); No "" when there is none
}

// DayRow is skill.ts DayRow: one row of a day's list, in the owner's language.
type DayRow struct {
	Case    string
	StartMs int64
	What    string
	Who     string
	State   string
}

// LocalDate is core/time.ts LocalDate.
type LocalDate struct{ Year, Month, Day int }

// Iso is conversation.ts isoDate: "2026-11-16".
func (d LocalDate) Iso() string {
	return time.Date(d.Year, time.Month(d.Month), d.Day, 12, 0, 0, 0, time.UTC).Format("2006-01-02")
}

// AddDays is core/time.ts addDays.
func (d LocalDate) AddDays(n int) LocalDate {
	t := time.Date(d.Year, time.Month(d.Month), d.Day+n, 12, 0, 0, 0, time.UTC)
	return LocalDate{t.Year(), int(t.Month()), t.Day()}
}

// OwnerSkill is skill.ts OwnerSkill: the part every skill has.
type OwnerSkill interface {
	Name() string
	// Owns is routing.refs: does this case reference belong to the skill ("b-14", "limit:refund_limit", "listing:l-3")?
	Owns(ref string) bool
	// Prepare is skill.ts prepare; why is a PrepareRefusal when it cannot be done.
	Prepare(p assistant.Raw) (prep Prepared, why string)
	Execute(a assistant.Action) Executed
	Waiting() []WaitingItem
	// Problems is how many things are wrong (refunds that need the builder), for the mood.
	Problems() int
}

// TalkFactsSkill is a skill with its own numbers for the owner's talk (skill.ts `facts`): counts and money, never a customer's name or number.
type TalkFactsSkill interface {
	Facts(nowMs int64) []assistant.TalkSource
}

// PublicSkill is a skill with what customers may be told (skill.ts `publicContext`); the owner's talk reads it with no customer (phone "").
type PublicSkill interface {
	PublicContext(phone string, nowMs int64) []assistant.TalkSource
}

// DaySkill is a skill with a day's list (skill.ts `day`).
type DaySkill interface {
	Day(d LocalDate) []DayRow
}

// HoursSkill is a skill with opening hours (skill.ts `hours`): the opening and closing minute of that date's weekday; ok false when the shop is always closed that weekday.
type HoursSkill interface {
	Hours(d LocalDate) (open, close int, ok bool)
}

// DayNotice is skill.ts DayNotice: the assistant's line to one customer about their booking on a closed or reopened day; true when it went out.
type DayNotice func(caseID, phone string, startMs int64) bool

// Booked is one booking on a closed day: the owner calls the ones the message could not reach.
type Booked struct{ Case, Who string }

// CloseDaySkill is a skill whose days can be closed and opened again (skill.ts closeDay, reopenDay).
type CloseDaySkill interface {
	CloseDay(d LocalDate, notify DayNotice) (booked []Booked, told []string)
	ReopenDay(d LocalDate, asked []string, notify DayNotice) (told []string)
}

// MoveSkill is a skill whose cases the owner may move (skill.ts moveTarget, move): why is a MoveRefusal.
type MoveSkill interface {
	MoveTarget(caseID string, date *LocalDate, tm *language.TimePhrase) (startMs int64, why string)
	Move(caseID string, startMs int64) (fromMs, toMs int64, why string)
}

// AssistantHooks is what a template's agent hands its assistant for one step (wire.ts AgentAssistantDeps).
type AssistantHooks struct {
	// Skill is the template's own skill.
	Skill OwnerSkill
	// Bookings: the shop's kinds are a Bookings shop's (the router's reading and the help lines for them). Orders: an Orders shop's (the open orders besides; its skill is an
	// OpenSkill, assistantopen.go). Fees: a Fees centre's (who owes besides; its skill is an OweSkill, assistantowes.go).
	Bookings bool
	Orders   bool
	Fees     bool
	// Messaging is the agent's own (its owner route included): the assistant's say goes through it.
	Messaging messaging.Messaging
	// Log writes a record line for a case of the template (caseID "" or one that is not the template's: no case), as the agent's own log does.
	Log func(caseID, phone, action, outcome string, inputs any, more messaging.LogMore)
	// LanguageOf and OptedOut are a customer's language and STOP.
	LanguageOf func(phone string) string
	OptedOut   func(phone string) bool
	// Listen is the owner's voice note heard through the agent's shared listener (conversation.ts AssistantDeps.hearing: the same switches, day's count and month's spend as a
	// customer's); nil: voice is off for the shop, and the owner's voice note gets the line asking to type. It answers nil when nothing was listened to.
	Listen func(msg messaging.InboundMessage, audio *PageAudio) *voice.Heard
	// InForce is called when the owner's tap on a limit card changed a limit inside this step (limits-card.ts execute: applyInForce into the live settings), so the agent's own
	// checks obey the new value for the rest of the same step; nil: the template reads its limits only when a step starts.
	InForce func()
}

// InForce is a declared limit's value in force for this step (runtime-limits.ts apply: the file's value moved by the saved changes); ok false for a limit the template does not
// declare.
func (c *StepContext) InForce(id string) (int64, bool) {
	if c.rt == nil || c.Snap == nil {
		return 0, false
	}
	return c.rt.inForceIn(c.Snap, c.limitNS+id)
}

// Assistant is the owner's assistant of one step of a template's agent (conversation.ts createAssistant's return).
type Assistant struct{ c *conv }

// Assistant is the shop's assistant over this step's state, or nil when the shop has none (wire.ts: no "assistant" block in the settings).
func (c *StepContext) Assistant(h AssistantHooks) *Assistant {
	if c.rt == nil || c.Settings == nil || !c.Settings.HasAssistant {
		return nil
	}
	cv := c.rt.assistantFor(c.Snap, c.Rec, c.Now())
	cv.toPage = false
	cv.reading = assistant.OwnerReading{Bookings: h.Bookings, Orders: h.Orders, Fees: h.Fees}
	cv.skills = []OwnerSkill{h.Skill}
	// decision 65: in a shop of several parts the ONE assistant hosts every part's skill, in the shop's order after this part's own (parts.go)
	if len(c.coParts) > 0 {
		var co []AssistantHooks
		for _, f := range c.coParts {
			if hh, ok := f(); ok && hh.Skill != nil {
				co = append(co, hh)
				cv.skills = append(cv.skills, hh.Skill)
				cv.reading.Bookings, cv.reading.Orders, cv.reading.Fees = cv.reading.Bookings || hh.Bookings, cv.reading.Orders || hh.Orders, cv.reading.Fees || hh.Fees
			}
		}
		h = joinHooks(h, co)
	}
	cv.hooks = &h
	if lim := cv.limitsSkill(); lim != nil {
		cv.skills = append(cv.skills, lim)
		cv.reading.LimitRule = lim.looksLikeRule
	}
	cv.skills = append(cv.skills, listingsSkill{cv})
	return &Assistant{cv}
}

// OnOwnerMessage is conversation.ts onOwnerMessage on WhatsApp: false when the message is not the owner's (the caller checks the sender first).
func (a *Assistant) OnOwnerMessage(msg messaging.InboundMessage) (bool, error) {
	if msg.From != a.c.number {
		return false, nil
	}
	return true, a.c.onOwnerMessage(msg, "o:"+msg.ID)
}

// OnPageCard is conversation.ts onPageCard: a card's yes or no from the owner's page, by the card's id and the digest it showed.
func (a *Assistant) OnPageCard(id, digest, answer string) {
	a.c.onPage(func() { a.c.onPageCard(id, digest, answer) })
}

// OnPageMessage is conversation.ts onPageMessage: the owner's words from the talk box, answered on the page.
func (a *Assistant) OnPageMessage(id, text string, at int64) (err error) {
	a.c.onPage(func() {
		a.c.a.AddTalk("owner", text, a.c.now)
		err = a.c.onOwnerMessage(messaging.InboundMessage{ID: id, From: a.c.number, Text: text, Timestamp: at}, "o:"+id)
	})
	return err
}

// SetListen hands the assistant the agent's listener for the owner's voice notes (AssistantHooks.Listen), once the agent has made its assistant.
func (a *Assistant) SetListen(l func(msg messaging.InboundMessage, audio *PageAudio) *voice.Heard) {
	a.c.hooks.Listen = l
}

// HearOwner is conversation.ts hearOwner: the owner's voice note as words. nil: not listened to (no voice service, button mode, no allowance left); a message with no text: it
// could not be made out, and the owner was told to type it; otherwise the heard words, to be read like the owner's typed message (the fixed phrases first).
func (a *Assistant) HearOwner(msg messaging.InboundMessage) *messaging.InboundMessage {
	return a.c.hearOwner(msg, nil)
}

// OnPageVoice is conversation.ts onPageVoice: a recording the owner made on their page (nil when this process no longer holds it: the owner is asked to type), heard by the same
// listener as their WhatsApp notes, then read like the talk box's words; everything is shown on the page.
func (a *Assistant) OnPageVoice(id string, audio *PageAudio) (err error) {
	c := a.c
	c.onPage(func() {
		msg := messaging.InboundMessage{ID: id, From: c.number, Timestamp: c.now, VoiceNote: true}
		var heard *messaging.InboundMessage
		if audio != nil {
			heard = c.hearOwner(msg, audio)
		}
		if heard == nil {
			c.say("voice_unheard") // not listened to (the recording is gone, button mode, no allowance): type it
			return
		}
		if heard.Text == "" {
			return // could not be made out: hearOwner said so
		}
		c.a.AddTalk("owner", heard.Text, c.now)
		err = c.onOwnerMessage(*heard, "o:"+heard.ID)
	})
	return err
}

func (c *conv) hearOwner(msg messaging.InboundMessage, audio *PageAudio) *messaging.InboundMessage {
	if c.hooks == nil || c.hooks.Listen == nil {
		return nil
	}
	h := c.hooks.Listen(msg, audio)
	if h == nil {
		return nil
	}
	// what listening cost goes on an owner_assistant line now, whatever the words turn out to be (a fixed phrase such as "today" never reaches the read line), in the shape the
	// cost meter prices; the listener already added it to the month's AI spend
	refs := map[string]string{"intent": "voice_note"}
	if !h.OK {
		for k, v := range voice.FailedMarks(*h) {
			refs[k] = v
		}
		c.logLine("owner_assistant", "confirmed", map[string]any{"voiceNote": true}, refs, "the owner's voice note could not be made out; they were asked to type it, and the audio was not kept")
		c.say("voice_unheard")
		out := msg
		out.Text = ""
		return &out
	}
	for k, v := range voice.Marks(*h) {
		refs[k] = v
	}
	for k, v := range voice.SpeechRead(*h) {
		refs[k] = v
	}
	c.logLine("owner_assistant", "confirmed", map[string]any{"voiceNote": true}, refs, "the owner's voice note, heard as words; they go on as if typed (the fixed phrases first, then the assistant), and the audio was not kept")
	return &messaging.InboundMessage{ID: msg.ID, From: msg.From, Text: h.Text, Timestamp: msg.Timestamp}
}

