// Shown is what a card says, from the same fields as its action (skill.ts Prepared.shown).
type Shown struct {
	Who, What   string
	AmountPaise int64
	Words       string // a message's words, shown as typed
	HasWords    bool
	Limit       *LimitCardView // a limit card: the rule, its value now and the proposed one
}

// Prepared is skill.ts Prepared when ok: the exact action and what the owner is shown.
type Prepared struct {
	Action     assistant.Action
	Shown      Shown
	AboveLimit bool
}

// Executed is skill.ts Executed: whether it worked and the note the owner's answer is worded by (done, held_by_guard, owed_by_owner, sent, failed, not_sent).
type Executed struct {
	OK   bool
	Note string
}

// WaitingItem is skill.ts WaitingItem: something that waits for the owner, as a card can show it.
type WaitingItem struct {
	Case, Kind, Who, What string
	AmountPaise           int64
	Money                 bool   // it is about money (every Bookings item is)
	Yes, No               string // the owner's own fixed replies ("approve" / "deny"); No "" when there is none
}

// DayRow is skill.ts DayRow: one row of a day's list, in the owner's language.
type DayRow struct {
	Case    string
	StartMs int64
	What    string
	Who     string
	State   string
}

// LocalDate is core/time.ts LocalDate.
type LocalDate struct{ Year, Month, Day int }

// Iso is conversation.ts isoDate: "2026-11-16".
func (d LocalDate) Iso() string { return time.Date(d.Year, time.Month(d.Month), d.Day, 12, 0, 0, 0, time.UTC).Format("2006-01-02") }

// AddDays is core/time.ts addDays.
func (d LocalDate) AddDays(n int) LocalDate {
	t := time.Date(d.Year, time.Month(d.Month), d.Day+n, 12, 0, 0, 0, time.UTC)
	return LocalDate{t.Year(), int(t.Month()), t.Day()}
}

// OwnerSkill is skill.ts OwnerSkill: the part every skill has.
type OwnerSkill interface {
	Name() string
	// Owns is routing.refs: does this case reference belong to the skill ("b-14", "limit:refund_limit", "listing:l-3")?
	Owns(ref string) bool
	// Prepare is skill.ts prepare; why is a PrepareRefusal when it cannot be done.
	Prepare(p assistant.Raw) (prep Prepared, why string)
	Execute(a assistant.Action) Executed
	Waiting() []WaitingItem
	// Problems is how many things are wrong (refunds that need the builder), for the mood.
	Problems() int
}

// DaySkill is a skill with a day's list (skill.ts `day`).
type DaySkill interface {
	Day(d LocalDate) []DayRow
}

// HoursSkill is a skill with opening hours (skill.ts `hours`): the opening and closing minute of that date's weekday; ok false when the shop is always closed that weekday.
type HoursSkill interface {
	Hours(d LocalDate) (open, close int, ok bool)
}

// DayNotice is skill.ts DayNotice: the assistant's line to one customer about their booking on a closed or reopened day; true when it went out.
type DayNotice func(caseID, phone string, startMs int64) bool

// Booked is one booking on a closed day: the owner calls the ones the message could not reach.
type Booked struct{ Case, Who string }

// CloseDaySkill is a skill whose days can be closed and opened again (skill.ts closeDay, reopenDay).
type CloseDaySkill interface {
	CloseDay(d LocalDate, notify DayNotice) (booked []Booked, told []string)
	ReopenDay(d LocalDate, asked []string, notify DayNotice) (told []string)
}

// MoveSkill is a skill whose cases the owner may move (skill.ts moveTarget, move): why is a MoveRefusal.
type MoveSkill interface {
	MoveTarget(caseID string, date *LocalDate, tm *language.TimePhrase) (startMs int64, why string)
	Move(caseID string, startMs int64) (fromMs, toMs int64, why string)
}

// AssistantHooks is what a template's agent hands its assistant for one step (wire.ts AgentAssistantDeps).
type AssistantHooks struct {
	// Skill is the template's own skill.
	Skill OwnerSkill
	// Bookings: the shop's kinds are a Bookings shop's (the router's reading and the help lines for them).
	Bookings bool
	// Messaging is the agent's own (its owner route included): the assistant's say goes through it.
	Messaging messaging.Messaging
	// Log writes a record line for a case of the template (caseID "" or one that is not the template's: no case), as the agent's own log does.
	Log func(caseID, phone, action, outcome string, inputs any, more messaging.LogMore)
	// LanguageOf and OptedOut are a customer's language and STOP.
	LanguageOf func(phone string) string
	OptedOut   func(phone string) bool
}

// InForce is a declared limit's value in force for this step (runtime-limits.ts apply: the file's value moved by the saved changes); ok false for a limit the template does not
// declare.
func (c *StepContext) InForce(id string) (int64, bool) {
	if c.rt == nil || c.Snap == nil {
		return 0, false
	}
	return c.rt.inForceIn(c.Snap, id)
}

// Assistant is the owner's assistant of one step of a template's agent (conversation.ts createAssistant's return).
type Assistant struct{ c *conv }

// Assistant is the shop's assistant over this step's state, or nil when the shop has none (wire.ts: no "assistant" block in the settings).
func (c *StepContext) Assistant(h AssistantHooks) *Assistant {
	if c.rt == nil || c.Settings == nil || !c.Settings.HasAssistant {
		return nil
	}
	cv := c.rt.assistantFor(c.Snap, c.Rec, c.Now())
	cv.hooks = &h
	cv.toPage = false
	cv.reading = assistant.OwnerReading{Bookings: h.Bookings}
	cv.skills = []OwnerSkill{h.Skill}
	if lim := cv.limitsSkill(); lim != nil {
		cv.skills = append(cv.skills, lim)
		cv.reading.LimitRule = lim.looksLikeRule
	}
	cv.skills = append(cv.skills, listingsSkill{cv})
	return &Assistant{cv}
}

// OnOwnerMessage is conversation.ts onOwnerMessage on WhatsApp: false when the message is not the owner's (the caller checks the sender first).
func (a *Assistant) OnOwnerMessage(msg messaging.InboundMessage) (bool, error) {
	if msg.From != a.c.number {
		return false, nil
	}
	return true, a.c.onOwnerMessage(msg, "o:"+msg.ID)
}

// OnPageCard is conversation.ts onPageCard: a card's yes or no from the owner's page, by the card's id and the digest it showed.
func (a *Assistant) OnPageCard(id, digest, answer string) {
	a.c.onPage(func() { a.c.onPageCard(id, digest, answer) })
}

// OnPageMessage is conversation.ts onPageMessage: the owner's words from the talk box, answered on the page.
func (a *Assistant) OnPageMessage(id, text string, at int64) (err error) {
	a.c.onPage(func() {
		a.c.a.AddTalk("owner", text, a.c.now)
		err = a.c.onOwnerMessage(messaging.InboundMessage{ID: id, From: a.c.number, Text: text, Timestamp: at}, "o:"+id)
	})
	return err
}

// OnTick is conversation.ts onTick.
func (a *Assistant) OnTick() { a.c.onTick() }

