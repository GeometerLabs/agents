// assistant is readAssistantSettings: the `assistant` block, checked, and returned as the checked form (`morningAt`, the character, `talk` only when it is off).
func (r *reader) assistant(v any, given bool, s *Settings) {
	if !given {
		return
	}
	raw, ok := isObj(v)
	if !ok {
		r.add(`"assistant" must be an object (it may be empty: {} turns the shop's assistant on with its defaults).`)
		return
	}
	for _, k := range r.keys(raw, "/assistant") {
		if k != "morning" && k != "character" && k != "talk" {
			r.add(`"assistant" has "` + k + `", which is not a setting (morning, character, talk).`)
		}
	}
	var morning any = map[string]any{"hour": 8.0, "minute": 0.0} // DEFAULT_MORNING
	if has(raw, "morning") {
		if b, isB := raw["morning"].(bool); isB && !b {
			morning = nil
		} else {
			var at any
			if m, isM := isObj(raw["morning"]); isM {
				at = m["at"]
			}
			var hit []string
			if as, isS := at.(string); isS {
				hit = morningRe.FindStringSubmatch(as)
			}
			if hit == nil {
				r.add(`"assistant.morning" must be {"at": "HH:MM"} (24-hour, the shop's time) or false for no morning line.`)
			} else {
				h, _ := strconv.Atoi(hit[1])
				m, _ := strconv.Atoi(hit[2])
				morning = map[string]any{"hour": float64(h), "minute": float64(m)}
			}
		}
	}
	customers := true
	if has(raw, "talk") {
		t, isT := isObj(raw["talk"])
		bad := !isT
		if isT {
			for k := range t {
				bad = bad || k != "customers"
			}
			if has(t, "customers") {
				if _, isB := t["customers"].(bool); !isB {
					bad = true
				}
			}
		}
		if bad {
			r.add(`"assistant.talk" must be {"customers": true} or {"customers": false}: false turns the assistant's own answers off for customers (they get the menu), true is the default.`)
		} else if c, isB := t["customers"].(bool); isB && !c {
			customers = false
		}
	}
	character := r.character(raw["character"], has(raw, "character"))
	if character == nil {
		character = map[string]any{"style": "clay", "personality": "warm"} // defaultCharacter()
	}
	out := map[string]any{"morningAt": morning, "character": character}
	if !customers {
		out["talk"] = map[string]any{"customers": false}
	}
	s.Assistant = out
}

// character is readCharacter: a character setting, checked; a missing part takes its default. nil when it is left out or not an object.
func (r *reader) character(v any, given bool) map[string]any {
	if !given {
		return nil
	}
	raw, ok := isObj(v)
	if !ok {
		r.add(`"assistant.character" must be an object with a style (and, if you like, a name).`)
		return nil
	}
	keys := []string{"name", "style", "seed", "colour", "paint", "personality"}
	for _, k := range r.keys(raw, "/assistant/character") {
		if k == "look" {
			r.add(`"assistant.character.look" is no longer a setting: the character is a DiceBear "style", a "seed" and a "colour" (decision 47). Make it again in the panel's Character step.`)
		} else if !contains(keys, k) {
			r.add(`"assistant.character" has "` + k + `", which is not a setting (` + strings.Join(keys, ", ") + `). The assistant answers in text, so there is no voice to choose.`)
		}
	}
	name, nameOK := "", true
	if has(raw, "name") {
		if ns, isS := raw["name"].(string); isS {
			name = language.TrimJS(ns)
		} else {
			nameOK = false
		}
	}
	if !nameOK || (name != "" && !charNameRe.MatchString(name)) {
		r.add(`The character's "name" must be 1 to 24 letters (spaces, hyphens and apostrophes are fine; no digits), or left out.`)
	}
	styleIDs := make([]string, len(checkWords.Styles))
	for i, st := range checkWords.Styles {
		styleIDs[i] = st.ID
	}
	var style any = "clay"
	if has(raw, "style") {
		style = raw["style"]
	}
	styleS, styleIsS := style.(string)
	styleOK := styleIsS && contains(styleIDs, styleS)
	if !styleOK {
		r.add(`The character's "style" must be one of: ` + strings.Join(styleIDs, ", ") + ".")
	}
	out := map[string]any{"style": "clay", "personality": "warm"}
	if styleOK {
		out["style"] = styleS
	}
	if name != "" {
		out["name"] = name
	}
	if has(raw, "seed") {
		if ss, isS := raw["seed"].(string); !isS || !seedRe.MatchString(ss) {
			r.add(`The character's "seed" must be 1 to 80 small letters, digits and hyphens.`)
		} else {
			out["seed"] = ss
		}
	}
	if has(raw, "colour") {
		c := ""
		if cs, isS := raw["colour"].(string); isS {
			c = strings.ToLower(strings.TrimPrefix(cs, "#"))
		}
		info := checkWords.Styles[0]
		for _, st := range checkWords.Styles {
			if st.ID == out["style"] {
				info = st
			}
		}
		if !contains(info.Palette, c) {
			r.add(`The character's "colour" must be one of the ` + info.Name + ` colours (` + strings.Join(info.Palette, ", ") + `), or left out for DiceBear's own.`)
		} else {
			out["colour"] = c
		}
	}
	if has(raw, "paint") {
		if ps, isS := raw["paint"].(string); !isS || !contains(checkWords.Paints, ps) {
			r.add(`The character's "paint" must be one of: ` + strings.Join(checkWords.Paints, ", ") + `, or left out for the head's own green.`)
		} else {
			out["paint"] = ps
		}
	}
	if has(raw, "personality") {
		if ps, isS := raw["personality"].(string); !isS || !contains(checkWords.Personalities, ps) {
			r.add(`The character's "personality" must be one of: ` + strings.Join(checkWords.Personalities, ", ") + ".")
		} else {
			out["personality"] = ps
		}
	}
	return out
}

// ChatGuestWords is chat-guest.ts CHAT_GUEST: what the owner calls a guest of the shop's chat, in front of the guest's number ("Chat guest 3").
func ChatGuestWords(lang string) string { return checkWords.ChatGuest[lang] }

// ---- the checked tree ---------------------------------------------------------------------------------------------------------------------------------------------------------

func namesTree(names map[string][]string) map[string]any {
	out := map[string]any{}
	for lang, list := range names {
		l := make([]any, len(list))
		for j, n := range list {
			l[j] = n
		}
		out[lang] = l
	}
	return out
}

func cutoffTree(c Cutoff) map[string]any {
	return map[string]any{"daysBefore": float64(c.DaysBefore), "time": c.Time}
}

func slotsTree(slots []Slot) []any {
	out := make([]any, len(slots))
	for i, sl := range slots {
		t := map[string]any{"id": sl.ID, "from": sl.From, "to": sl.To}
		if sl.Names != nil {
			t["names"] = namesTree(sl.Names)
		}
		if sl.Cutoff != nil {
			t["cutoff"] = cutoffTree(*sl.Cutoff)
		}
		if sl.MaxOrders != nil {
			t["maxOrders"] = float64(*sl.MaxOrders)
		}
		out[i] = t
	}
	return out
}

func stringsTree(l []string) []any {
	out := make([]any, len(l))
	for i, s := range l {
		out[i] = s
	}
	return out
}

// Tree is the validated settings as the JSON value validateSettings returns: what the policy digest is of (ordersreport.PolicyDigest), and what the monthly report reads.
func (s *Settings) Tree() map[string]any {
	n := func(v int64) any { return float64(v) }
	menu := make([]any, len(s.Menu))
	for i, it := range s.Menu {
		menu[i] = map[string]any{"id": it.ID, "names": namesTree(it.Names), "priceInr": n(it.PriceInr), "dailyStock": n(it.DailyStock)}
	}
	payment := map[string]any{"module": s.Payment.Module}
	if s.Payment.Module == "upi" {
		payment["upi"] = map[string]any{"id": s.Payment.UpiID, "payee": s.Payment.Payee}
	}
	t := map[string]any{
		"name": s.Name, "timezone": s.Timezone, "languages": stringsTree(s.Languages), "menu": menu,
		"orders": map[string]any{"maxPerDay": n(s.Orders.MaxPerDay), "maxItemsPerOrder": n(s.Orders.MaxItemsPerOrder), "daysAhead": n(s.Orders.DaysAhead)},
		"cutoff": cutoffTree(s.Cutoff), "pickup": map[string]any{"slots": slotsTree(s.Pickup)},
		"advance":      map[string]any{"mode": s.Advance.Mode, "percent": n(s.Advance.Percent), "holdMinutes": n(s.Advance.HoldMinutes)},
		"cancellation": map[string]any{"windowHours": n(s.Cancellation.WindowHours)}, "refund": map[string]any{"limitInr": n(s.Refund.LimitInr)},
		"payment": payment, "owner": map[string]any{"whatsapp": s.Owner.Whatsapp, "language": s.Owner.Language, "approveOverInr": n(s.Owner.ApproveOverInr)},
	}
	if s.Reminder != nil {
		t["reminder"] = map[string]any{"hoursBefore": n(s.Reminder.HoursBefore)}
	}
	if s.Delivery != nil {
		t["delivery"] = map[string]any{"slots": slotsTree(s.Delivery.Slots), "area": stringsTree(s.Delivery.Area)}
	}
	if s.Approvers != nil {
		t["approvers"] = s.Approvers
	}
	if s.Assistant != nil {
		t["assistant"] = s.Assistant
	}
	if s.Plans != nil {
		types := make([]any, len(s.Plans.Types))
		for i, pt := range s.Plans.Types {
			days := make([]any, len(pt.Weekdays))
			for j, d := range pt.Weekdays {
				days[j] = float64(d)
			}
			types[i] = map[string]any{"id": pt.ID, "names": namesTree(pt.Names), "slotId": pt.SlotID, "weekdays": days, "priceInr": n(pt.PriceInr)}
		}
		t["plans"] = map[string]any{"types": types, "cutoff": cutoffTree(s.Plans.Cutoff), "credits": s.Plans.Credits}
	}
	if s.HasAddress {
		t["address"] = s.Address
	}
	return t
}

// CheckSettingsFile is validateSettings over the text of settings.json: the checked settings and their tree, or every problem in plain words (a file that is not JSON says so).
func CheckSettingsFile(raw []byte) (*Settings, map[string]any, []string) {
	var v any
	if err := json.Unmarshal(raw, &v); err != nil {
		return nil, nil, []string{"The settings file is not valid JSON: " + err.Error()}
	}
	in, ok := v.(map[string]any)
	if !ok {
		return nil, nil, []string{"The settings must be an object with the shop's name, menu, slots and so on."}
	}
	s, errs := ReadSettings(in, raw)
	if len(errs) > 0 {
		return nil, nil, errs
	}
	return s, s.Tree(), nil
}
