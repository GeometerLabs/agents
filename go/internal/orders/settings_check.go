var (
	personRe   = regexp.MustCompile(`^[a-z][a-z0-9-]{0,31}$`)
	charNameRe = regexp.MustCompile(`^[\p{L}\p{M}][\p{L}\p{M} '’-]{0,23}$`)
	seedRe     = regexp.MustCompile(`^[a-z0-9][a-z0-9-]{0,79}$`)
	morningRe  = regexp.MustCompile(`^([01]\d|2[0-3]):([0-5]\d)$`)
)

func digitsOf(s string) string {
	var b strings.Builder
	for _, c := range s {
		if c >= '0' && c <= '9' {
			b.WriteRune(c)
		}
	}
	return b.String()
}

// approvers is readApprovers(input.approvers, {ownerWhatsapp: owner?.whatsapp, refundLimitInr: refund?.limitInr}, errors). `given` tells a missing key from a JSON null; owner is
// "" and refundOK false when that block was not read.
func (r *reader) approvers(v any, given bool, owner string, refundOK bool, refundLimit int64, s *Settings) {
	if !given {
		return
	}
	const where = "approvers"
	before := len(r.errs)
	obj, ok := isObj(v)
	if !ok {
		r.add(`"` + where + `" must look like {"people": [{"id": "ravi", "whatsapp": "+919800000002", "language": "hi"}], "twoAboveInr": 2000}. Leave it out and the owner alone approves.`)
		return
	}
	for _, k := range r.keys(obj, "/approvers") {
		if k != "people" && k != "twoAboveInr" {
			r.add(`I don't know what "` + k + `" means in "` + where + `". Allowed: people, twoAboveInr.`)
		}
	}
	list, isList := obj["people"].([]any)
	if !isList || len(list) == 0 || len(list) > checkWords.MaxPeople {
		r.addf(`"%s.people" must list 1 to %d people besides the owner, each with an id, a WhatsApp number and a language.`, where, checkWords.MaxPeople)
		return
	}
	people := []any{}
	ids := map[string]bool{}
	numbers := map[string]bool{}
	if owner != "" {
		numbers[digitsOf(owner)] = true
	}
	for i, raw := range list {
		at := fmt.Sprintf("%s.people[%d]", where, i)
		p, ok := isObj(raw)
		if !ok {
			r.add(at + ` must be {"id": "ravi", "whatsapp": "+919800000002", "language": "hi"}.`)
			continue
		}
		for _, k := range r.keys(p, "/approvers/people/"+strconv.Itoa(i)) {
			if k != "id" && k != "whatsapp" && k != "language" {
				r.add(`I don't know what "` + k + `" means in ` + at + `. Allowed: id, whatsapp, language.`)
			}
		}
		id, idIsS := p["id"].(string)
		switch {
		case !idIsS || !personRe.MatchString(id) || id == checkWords.OwnerApprover:
			r.add(at + `.id must be a short name in lower-case letters, digits and hyphens, starting with a letter (for example "ravi"), and not "` + checkWords.OwnerApprover + `".`)
		case ids[id]:
			r.add(at + `.id "` + id + `" is listed twice: each person has their own id.`)
		default:
			ids[id] = true
		}
		wa, waIsS := p["whatsapp"].(string)
		switch {
		case !waIsS || !phoneRe.MatchString(wa):
			r.add(at + ".whatsapp must start with + and the country code, then digits only, for example +919800000002.")
		case numbers[digitsOf(wa)]:
			r.add(at + ".whatsapp is already the owner's or another person's number: each person answers from their own phone.")
		default:
			numbers[digitsOf(wa)] = true
		}
		var lang any = "en" // `p.language ?? "en"`
		if p["language"] != nil {
			lang = p["language"]
		}
		ls, langIsS := lang.(string)
		langOK := langIsS && contains(runtime.LANGUAGES, ls)
		if !langOK {
			r.add(at + ".language must be one of " + strings.Join(runtime.LANGUAGES, ", ") + ".")
		}
		if idIsS && waIsS && langOK {
			people = append(people, map[string]any{"id": id, "whatsapp": wa, "language": ls})
		}
	}
	var two any
	if has(obj, "twoAboveInr") {
		n, whole := isWhole(obj["twoAboveInr"])
		switch {
		case !whole || n < 0 || n > 10_000_000:
			r.add(`"` + where + `.twoAboveInr" must be a whole number of rupees: refunds above it need two different people.`)
		case refundOK && n < float64(refundLimit):
			l := strconv.FormatInt(refundLimit, 10)
			r.add(`"` + where + `.twoAboveInr" (₹` + num(n) + `) is below the refund limit (₹` + l + `). Up to the refund limit the agent refunds alone, so two people can only be asked above it: make it ₹` + l + ` or more.`)
		default:
			two = n
		}
	}
	if len(r.errs) > before {
		return
	}
	out := map[string]any{"people": people}
	if two != nil {
		out["twoAboveInr"] = two
	}
	s.Approvers = out
}

