const paymentExamples = `{"module": "upi", "upi": {"id": "glowsalon@okicici", "payee": "Glow Salon"}} or {"module": "razorpay"}`

func (r *reader) payment(in map[string]any, s *Settings) {
	if !has(in, "payment") {
		r.add(`Add how customers pay ("payment"). UPI is the default: {"module": "upi", "upi": {"id": "glowsalon@okicici", "payee": "Glow Salon"}}, with the shop's own UPI ID and the name its customers see. A shop with its own gateway account names it instead: {"module": "razorpay"}.`)
		return
	}
	m, ok := isObj(in["payment"])
	if !ok {
		r.add(`The payment module ("payment") must look like ` + paymentExamples + ".")
		return
	}
	module, _ := m["module"].(string)
	if _, known := checkWords.Capabilities[module]; !known || (module != "upi" && module != "razorpay") {
		r.add("The payment module " + jsJSONOrUndefined(m, "module") + ` is not one I know. Use "upi" or "razorpay": ` + paymentExamples + ".")
		return
	}
	for _, k := range r.keys(m, "/payment") {
		if k != "module" && k != "upi" {
			r.add(`I don't know what "` + k + `" means in the payment module. Allowed: module, upi.`)
		}
	}
	if module == "razorpay" {
		if has(m, "upi") {
			r.add(`A Razorpay shop has no UPI ID in its settings: take out "payment.upi", or set "payment.module" to "upi".`)
			return
		}
		s.Payment = Payment{Module: "razorpay"}
		return
	}
	u, ok := isObj(m["upi"])
	if !ok {
		r.add(`A UPI shop needs its UPI ID and the payee name: "payment": {"module": "upi", "upi": {"id": "glowsalon@okicici", "payee": "Glow Salon"}}.`)
		return
	}
	for _, k := range r.keys(u, "/payment/upi") {
		if k != "id" && k != "payee" {
			r.add(`I don't know what "` + k + `" means in "payment.upi". Allowed: id, payee.`)
		}
	}
	id, _ := u["id"].(string) // not text is "" here: vpaProblem says "Add the shop's UPI ID" for both
	payee, _ := u["payee"].(string)
	idIssue, payeeIssue := upi.VpaProblem(id), upi.PayeeProblem(payee)
	if idIssue != "" {
		r.add(`"payment.upi.id": ` + idIssue)
	}
	if payeeIssue != "" {
		r.add(`"payment.upi.payee": ` + payeeIssue)
	}
	if idIssue == "" && payeeIssue == "" {
		s.Payment = Payment{Module: "upi", UpiID: upi.NormaliseVpa(id), Payee: language.TrimJS(payee)}
	}
}

// jsJSONOrUndefined is JSON.stringify(obj[key]) in a template literal: "undefined" for a missing key.
func jsJSONOrUndefined(m map[string]any, key string) string {
	if !has(m, key) {
		return "undefined"
	}
	return jsJSON(m[key])
}

