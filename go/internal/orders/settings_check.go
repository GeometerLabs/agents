package orders

// The readers every template shares that validateSettings (templates/commerce/orders/src/settings.ts) calls, and the CHECKED TREE it returns.
//
//   - payment: modules/payments/providers/index.ts readPaymentSettings with the two providers there are (upi, razorpay), their sentences, and upi/link.ts's checks of a UPI ID and a
//     payee (internal/payments/upi: VpaProblem, PayeeProblem, NormaliseVpa).
//   - approvers: modules/approvals/people.ts readApprovers (who else may approve a refund Guard holds, and the amount above which two must).
//   - assistant: modules/assistant/settings.ts readAssistantSettings and character.ts readCharacter.
// These are a copy of internal/bookings/settings_check.go's, with Orders' inputs (the refund limit is `refund.limitInr`, the owner's number only when the whole owner block
// was read). Bookings keeps them unexported and this package may not import it; Deferred.md names them as the first thing to move into one shared package.
//
// Why a tree: the report's policy digest (ordersreport.PolicyDigest) is the digest of the settings AS VALIDATED, not as the file was written: validateSettings fills the defaults,
// trims the names, keeps an item's names in the shop's languages only, lower-cases a UPI ID and hands `approvers` and `assistant` back in their checked forms. (*Settings).Tree
// writes the validated settings as that JSON tree (numbers as float64, as JSON.parse reads them); testdata/settings-vectors.json holds it and its digest equal to the TypeScript's.
//
// The lists the character and the approvers are checked against, the most a day's refunds may come to, LOWEST_LINK_INR, each payment module's capabilities and the chat guest's
// words are the TypeScript's own (settings_check.json, generated by go/scripts/gen_orders_settings.ts): nothing is retyped.
//
// Where Go and JavaScript differ: the character's name is checked with RE2's `\p{L}\p{M}` (the classes the `u` flag gives); `digits` keeps ASCII digits only, as `\D` with `u` does.

