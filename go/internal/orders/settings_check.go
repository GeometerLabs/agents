//go:embed settings_check.json
var checkJSON []byte

// capsJSON is one provider's capabilities as providers/<name>/index.ts declares them.
type capsJSON struct {
	ConfirmsAutomatically bool `json:"confirmsAutomatically"`
	RefundsAutomatically  bool `json:"refundsAutomatically"`
	TakesPartPayments     bool `json:"takesPartPayments"`
	Cancels               bool `json:"cancels"`
	ReadsBack             bool `json:"readsBack"`
	ReadsSettlements      bool `json:"readsSettlements"`
}

// checkWords is settings_check.json.
var checkWords = func() (w struct {
	Styles []struct {
		ID      string   `json:"id"`
		Name    string   `json:"name"`
		Palette []string `json:"palette"`
	} `json:"styles"`
	Personalities     []string            `json:"personalities"`
	Paints            []string            `json:"paints"`
	MaxPeople         int                 `json:"maxPeople"`
	OwnerApprover     string              `json:"ownerApprover"`
	RefundPaisePerDay int64               `json:"refundPaisePerDay"`
	LowestLinkInr     int64               `json:"lowestLinkInr"`
	Capabilities      map[string]capsJSON `json:"capabilities"`
	DefaultModule     string              `json:"defaultModule"`
	ChatGuest         map[string]string   `json:"chatGuest"`
}) {
	if err := json.Unmarshal(checkJSON, &w); err != nil {
		panic("settings_check.json: " + err.Error())
	}
	return
}()

