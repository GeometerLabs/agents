#!/usr/bin/env python3
# Writes internal/listings/claimwords_gen.go from the TypeScript source of the claim words (modules/assistant/talk-check.ts), so the Go runtime never has its own retyped copy of
# the four-language word lists: when the TypeScript lists change, run this again. Run from the repository root: python3 go/scripts/gen_claimwords.py
#
# Each TypeScript pattern has the shape  NB(?:A)NL|B  where NB and NL are the "a word's start / end" look-behind and look-ahead (JavaScript only; Go's regexp has neither).
# The generator splits it into Bounded (A, which must match as a whole word) and Rest (B, which may match anywhere); the Go side checks the word edges itself.
import re, sys

src = open("modules/assistant/talk-check.ts", encoding="utf8").read()
lines = []
for kind, name in (("assure", "Assure"), ("speaks_for_owner", "SpeaksForOwner"), ("money_off", "MoneyOff")):
    m = re.search(r"\n  " + kind + r": U\(`(.*?)`\),\n", src, re.S)
    if not m:
        sys.exit("could not find the " + kind + " words in talk-check.ts")
    pat = m.group(1).replace("${NB}", "").replace("${NL}", "\x00").replace("\\\\", "\\")
    bounded, _, rest = pat.partition("\x00")
    rest = rest.lstrip("|")
    # `free(?! (?:time|...))`: Go has no look-ahead, so the words that must NOT follow "free" are handed over as a list
    not_after = []
    n = re.search(r"free\(\?! \(\?:([^)]*)\)\)", bounded)
    if n:
        not_after = n.group(1).split("|")
        bounded = bounded.replace(n.group(0), "free")
    lines.append((name, bounded, rest, not_after))

out = ["// Code generated by go/scripts/gen_claimwords.py from modules/assistant/talk-check.ts; DO NOT EDIT.", "// The claim words (promises, speaking for the owner, money off) in four languages, as the TypeScript source writes them.", "", "package listings", ""]
out.append("type claimWords struct {\n\t// Bounded must match as a whole word (a letter or mark on either side cancels it); Rest may match anywhere.\n\tBounded, Rest string\n\t// NotAfter: a Bounded match of \"free\" followed by one of these words is not a claim (\"free time\").\n\tNotAfter []string\n}\n")
out.append("var claimWordTable = map[string]claimWords{")
for name, bounded, rest, not_after in lines:
    na = ", ".join('"' + w + '"' for w in not_after)
    out.append("\t\"%s\": {Bounded: `%s`, Rest: `%s`, NotAfter: []string{%s}}," % (name, bounded, rest, na))
out.append("}")
open("go/internal/listings/claimwords_gen.go", "w", encoding="utf8").write("\n".join(out) + "\n")
print("wrote go/internal/listings/claimwords_gen.go")
