// Writes what the Go report package (go/internal/report) takes from the TypeScript as DATA, made by RUNNING it, never retyped:
//   words/words.json.gz     the report's plain words (INNOVATOR, SETTLED_BY_*, CHECK_GENUINE, SCAN_SUMMARY, WHAT_THIS_CHECKS), the signed summary's LAYOUTS, the page's style sheet,
//                           the claim rules (BANNED, as pattern source and flags) and the sample summary link. A word that is a function (SETTLED_BY_WORD) is carried as a template
//                           with a {0} slot after lib_words.ts has checked it does nothing but put its argument in.
//   graphemes_gen.go        the Unicode properties the Go grapheme cutter needs and Go's `unicode` package does not have (Prepend, Extended_Pictographic, and the three
//                           Indic_Conjunct_Break classes), found by asking Node's own Intl.Segmenter about every code point, so Go cuts where Node cuts.
// Run from the repository root:  node go/scripts/gen_report_words.ts   (--check only compares; the test words-fresh fails when it was not run after a change)
import { readFileSync, writeFileSync, mkdirSync, existsSync } from "node:fs";
import { dirname, join } from "node:path";
import { fileURLToPath } from "node:url";
import { gunzipSync } from "node:zlib";
import { LANGUAGES } from "../../modules/language/languages.ts";
import { CHECK_GENUINE, INNOVATOR, SCAN_SUMMARY, SETTLED_BY_SOMEONE, SETTLED_BY_WORD } from "../../modules/report/text.ts";
import { WHAT_THIS_CHECKS } from "../../modules/report/what-this-checks.ts";
import { LAYOUTS, SAMPLE_DIGEST, SAMPLE_SUMMARY_LINK } from "../../modules/report/summary.ts";
import { CSS } from "../../modules/report/page.ts";
import { BANNED } from "../../modules/report/claims.ts";
import { pack, slotted } from "./lib_words.ts";

const here = dirname(fileURLToPath(import.meta.url));
const INTERNAL = join(here, "..", "internal");
export const OUT = INTERNAL;

function words(): Buffer {
  return pack({
    innovator: INNOVATOR,
    settledByWord: Object.fromEntries(LANGUAGES.map((l) => [l, slotted((who) => SETTLED_BY_WORD[l](who), 1)])),
    settledBySomeone: SETTLED_BY_SOMEONE,
    checkGenuine: CHECK_GENUINE,
    scanSummary: SCAN_SUMMARY,
    whatThisChecks: WHAT_THIS_CHECKS,
    layouts: LAYOUTS,
    css: CSS,
    banned: Object.fromEntries(Object.entries(BANNED).map(([k, list]) => [k, list.map((re) => ({ source: re.source, flags: re.flags }))])),
    sampleLink: SAMPLE_SUMMARY_LINK,
    sampleDigest: SAMPLE_DIGEST,
  });
}

// ---- the properties Go lacks, from Node's segmenter ----
const seg = new Intl.Segmenter(undefined, { granularity: "grapheme" });
export const clusters = (s: string): number => { let n = 0; for (const _ of seg.segment(s)) n++; return n; };
const VIRAMA = "्"; // Devanagari virama, a Linker
const KA = "क"; // Devanagari KA, a Consonant

function ranges(cps: number[]): [number, number][] {
  const out: [number, number][] = [];
  for (const cp of cps) { const last = out[out.length - 1]; if (last && last[1] === cp - 1) last[1] = cp; else out.push([cp, cp]); }
  return out;
}

export function probe(): { prepend: [number, number][]; extPict: [number, number][]; consonant: [number, number][]; linker: [number, number][]; extend: [number, number][] } {
  const prepend: number[] = [], extPict: number[] = [], consonant: number[] = [], linker: number[] = [], extend: number[] = [];
  const pict = /^\p{Extended_Pictographic}$/u;
  for (let cp = 0; cp <= 0x10ffff; cp++) {
    if (cp >= 0xd800 && cp <= 0xdfff) continue;
    const ch = String.fromCodePoint(cp);
    if (pict.test(ch)) extPict.push(cp);
    if (clusters(ch + "a") === 1 && cp !== 0x0d) prepend.push(cp); // a character that holds on to the next one (CR LF is not "a")
    if (clusters(KA + ch + KA) === 1) linker.push(cp); // joins two consonants: a Linker
    if (clusters(ch + VIRAMA + KA) === 1 && clusters(KA + VIRAMA + ch) === 1) consonant.push(cp);
  }
  const isLinker = new Set(linker);
  for (let cp = 0; cp <= 0x10ffff; cp++) {
    if (cp >= 0xd800 && cp <= 0xdfff || isLinker.has(cp)) continue;
    const ch = String.fromCodePoint(cp);
    if (clusters("a" + ch) === 1 && clusters(KA + VIRAMA + ch + KA) === 1) extend.push(cp);
  }
  return { prepend: ranges(prepend), extPict: ranges(extPict), consonant: ranges(consonant), linker: ranges(linker), extend: ranges(extend) };
}

function goTables(): string {
  const p = probe();
  const show = (name: string, what: string, r: [number, number][]) =>
    `// ${what}\nvar ${name} = [][2]rune{${r.map(([a, b]) => `{0x${a.toString(16)}, 0x${b.toString(16)}}`).join(", ")}}\n`;
  return `// Code generated by scripts/gen_report_words.ts from Node's Intl.Segmenter (${process.versions.icu ? "ICU " + process.versions.icu + ", Unicode " + process.versions.unicode : "ICU"}). DO NOT EDIT.
// The Unicode properties graphemes.go needs that Go's unicode package does not have, found by asking the segmenter itself about each code point.
package report

${show("prependRanges", "Grapheme_Cluster_Break=Prepend: a character that stays with the one after it", p.prepend)}
${show("extPictRanges", "Extended_Pictographic (the emoji ZWJ sequence rule)", p.extPict)}
${show("incbConsonantRanges", "Indic_Conjunct_Break=Consonant", p.consonant)}
${show("incbLinkerRanges", "Indic_Conjunct_Break=Linker (the viramas)", p.linker)}
${show("incbExtendRanges", "Indic_Conjunct_Break=Extend: marks a conjunct may hold between its consonants", p.extend)}`;
}

export function generate(): Map<string, Buffer | string> {
  const out = new Map<string, Buffer | string>();
  out.set("report/words/words.json.gz", words());
  out.set("report/graphemes_gen.go", goTables());
  return out;
}

export function staleFiles(root = INTERNAL): string[] {
  return [...generate()].filter(([name, data]) => {
    if (!existsSync(join(root, name))) return true;
    const have = readFileSync(join(root, name));
    // a gzip file's bytes carry no clock here (Node writes none), but compare what is inside, so a different zlib build is not "stale"
    return name.endsWith(".gz") ? !gunzipSync(have).equals(gunzipSync(data as Buffer)) : have.toString("utf8") !== data;
  }).map(([name]) => name);
}

if (process.argv[1] === fileURLToPath(import.meta.url)) {
  if (process.argv.includes("--check")) {
    const stale = staleFiles();
    if (stale.length) { console.error(`out of date: ${stale.join(", ")}  (run node go/scripts/gen_report_words.ts)`); process.exit(1); }
  } else {
    for (const [name, data] of generate()) { mkdirSync(dirname(join(INTERNAL, name)), { recursive: true }); writeFileSync(join(INTERNAL, name), data); }
  }
}
